"""Tests for the projection of a trade log onto the two return series.

The four kinds required by ``04`` are present and labelled by class:

``TestAnalyticCases``
    Closed form results: the dilution identity of ``02`` section 1.6, the
    single non zero period collapsing to ``1/sqrt(T)``, and the algebraic
    equivalence of the two readings of the ``CURRENT_EQUITY`` composition rule.

``TestInvariances``
    Scale, translation and within period permutation.

``TestDegenerateCases``
    Empty log, one trade, all winners, all losers, scratch trade, ruin,
    calendar not covering the log, empty feasible set, forced grid.

``TestSyntheticRecovery``
    Data generated by a process with declared parameters, seed fixed, and the
    parameters recovered from the projection within sampling error.
"""

