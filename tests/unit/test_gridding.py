class TestSyntheticRecovery:
    def test_bernoulli_arrival_rate_is_recovered_in_the_active_fraction(self) -> None:
        """Arrivals generated at a declared rate, recovered from the projection."""
        rng = np.random.default_rng(101)
        days = weekday_sequence(datetime(2020, 1, 1, tzinfo=UTC), 2_000)
        p_true = 0.30
        drawn = rng.random(len(days)) < p_true
        drawn[0] = drawn[-1] = True
        idx = np.flatnonzero(drawn)
        log = build_log([days[i] for i in idx], rng.normal(300.0, 1_100.0, idx.size))
        grid = period_returns(
            log,
            sentinel_calendar(days[0], days[-1]),
            period=Period.DAILY,
            basis=Basis.FIXED_INITIAL,
            initial_capital=CAPITAL,
        )
        standard_error = np.sqrt(p_true * (1 - p_true) / len(days))
        assert abs(grid.active_fraction - p_true) < 4.0 * standard_error

    def test_declared_edge_is_recovered_in_the_grid_mean(self) -> None:
        """Mean P&L per period recovered from a process with a declared mean."""
        rng = np.random.default_rng(103)
        days = weekday_sequence(datetime(2020, 1, 1, tzinfo=UTC), 1_500)
        mu, sigma = 250.0, 900.0
        pnl = rng.normal(mu, sigma, len(days))
        grid = period_returns(
            build_log(days, pnl),
            sentinel_calendar(days[0], days[-1]),
            period=Period.DAILY,
            basis=Basis.FIXED_INITIAL,
            initial_capital=CAPITAL,
        )
        values = np.asarray(grid.values)
        standard_error = sigma / CAPITAL / np.sqrt(len(days))
        assert abs(values.mean() - mu / CAPITAL) < 4.0 * standard_error

    def test_ladder_choice_is_stable_across_seeds_for_a_declared_process(self) -> None:
        """The rule must not flip rung on resampling noise alone."""
        days = weekday_sequence(datetime(2020, 1, 1, tzinfo=UTC), 1_000)
        cal = sentinel_calendar(days[0], days[-1])
        chosen = set()
        for seed in range(201, 211):
            rng = np.random.default_rng(seed)
            drawn = rng.random(len(days)) < 0.40
            drawn[0] = drawn[-1] = True
            idx = np.flatnonzero(drawn)
            log = build_log([days[i] for i in idx], rng.normal(200.0, 1_000.0, idx.size))
            chosen.add(
                select_grid(log, cal, basis=Basis.FIXED_INITIAL, initial_capital=CAPITAL).period
            )
        assert chosen == {Period.DAILY}

    def test_thresholds_are_the_ones_the_constants_declare(self) -> None:
        """Guards against a threshold drifting away from its written derivation."""
        assert MIN_ACTIVE_FRACTION == 0.15
        assert MIN_PERIODS == 60


